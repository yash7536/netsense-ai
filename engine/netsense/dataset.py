"""Generate the dataset the React app consumes.

The Python engine is the source of truth: the seed JSON under ``engine/seed`` (authored
content) and the generated telemetry both flow from here into
``app/src/data/generated/``. Those files are committed, so the app (and its Vercel
build) never needs Python at build time; ``check`` fails if they drift from what the
engine would produce.
"""

from __future__ import annotations

import json
from pathlib import Path

from .pipeline import EngineRun, run_engine
from .profiles import LINK_PROFILES

REPO_ROOT = Path(__file__).resolve().parents[2]
APP_DATA_DIR = REPO_ROOT / "app" / "src" / "data" / "generated"
RESULTS_DIR = REPO_ROOT / "docs" / "results"

GENERATED_README = """# Generated data — do not edit by hand

These files are produced by the Python engine in `engine/` and committed so the
React app can import them directly:

- `links.json`, `predictions.json`, `incidents.json`, `engineers.json` — the authored
  demonstration seed (`engine/seed/`), validated by the engine.
- `telemetry.json` — synthetic 30-minute telemetry per link (`t = -48h … +12h`),
  generated by `engine/netsense/telemetry.py`. Not measured from any network.
- `drift-profiles.json` — which designed drift profile each link carries.

Regenerate: `cd engine && python -m netsense build-data`
Verify nothing drifted: `cd engine && python -m netsense check`
"""


def _num(x: float) -> int | float:
    """Drop the trailing '.0' on whole numbers so the output reads like the TypeScript literals."""
    return int(x) if float(x).is_integer() else x


def _dump_json(payload: object) -> str:
    return json.dumps(payload, indent=2, ensure_ascii=False) + "\n"


def _dump_telemetry(telemetry: dict[str, list]) -> str:
    """One telemetry sample per line, so the file stays reviewable."""
    lines = ["{"]
    link_ids = list(telemetry)
    for li, link_id in enumerate(link_ids):
        lines.append(f"  {json.dumps(link_id)}: [")
        points = telemetry[link_id]
        for pi, p in enumerate(points):
            body = {k: _num(v) for k, v in p.to_json().items()}
            comma = "," if pi < len(points) - 1 else ""
            lines.append(f"    {json.dumps(body)}{comma}")
        lines.append("  ]" + ("," if li < len(link_ids) - 1 else ""))
    lines.append("}")
    return "\n".join(lines) + "\n"


def app_files(run: EngineRun) -> dict[str, str]:
    """File name -> exact text content the engine produces for ``app/src/data/generated``."""
    return {
        "links.json": _dump_json(run.seed.links),
        "predictions.json": _dump_json(run.seed.predictions),
        "incidents.json": _dump_json(run.seed.incidents),
        "engineers.json": _dump_json(run.seed.engineers),
        "telemetry.json": _dump_telemetry(run.telemetry),
        "drift-profiles.json": _dump_json(LINK_PROFILES),
        "README.md": GENERATED_README,
    }


def write_app_data(run: EngineRun, out_dir: Path = APP_DATA_DIR) -> list[str]:
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for name, text in app_files(run).items():
        (out_dir / name).write_text(text, encoding="utf-8", newline="\n")
        written.append(name)
    return written


def check_app_data(run: EngineRun, out_dir: Path = APP_DATA_DIR) -> list[str]:
    """Return a list of problems; empty means the committed files match the engine.

    JSON files are compared as parsed values (robust to line-ending differences);
    the README is compared with normalised newlines.
    """
    problems: list[str] = []
    for name, expected in app_files(run).items():
        path = out_dir / name
        if not path.exists():
            problems.append(f"{name}: missing")
            continue
        actual = path.read_text(encoding="utf-8")
        if name.endswith(".json"):
            if json.loads(actual) != json.loads(expected):
                problems.append(f"{name}: differs from what the engine generates")
        elif actual.replace("\r\n", "\n") != expected:
            problems.append(f"{name}: differs from what the engine generates")
    return problems


def regenerate() -> EngineRun:
    return run_engine()
